const escapeHtml = (value) =>
  String(value)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");

const escapeText = (value) => String(value).replace(/\r?\n/g, "\n");

export function renderNotificationEmail({
  inquiryLabel,
  fields,
  submittedAt,
  replyTo,
}) {
  const safeFields = fields.filter(
    (field) => field.value !== undefined && field.value !== null && `${field.value}`.length > 0,
  );

  const rows = safeFields
    .map(
      (field) => `
        <tr>
          <td style="padding:10px 16px 10px 0;vertical-align:top;font-family:Helvetica,Arial,sans-serif;font-size:12px;letter-spacing:0.08em;text-transform:uppercase;color:#687386;width:38%;">${escapeHtml(field.label)}</td>
          <td style="padding:10px 0;vertical-align:top;font-family:Helvetica,Arial,sans-serif;font-size:15px;line-height:1.55;color:#101D32;white-space:pre-wrap;">${escapeHtml(field.value)}</td>
        </tr>`,
    )
    .join("");

  const html = `<!doctype html>
<html lang="en">
  <body style="margin:0;padding:0;background-color:#F5F6F8;">
    <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="background-color:#F5F6F8;padding:28px 12px;">
      <tr>
        <td align="center">
          <table role="presentation" width="100%" cellpadding="0" cellspacing="0" style="max-width:600px;background-color:#FFFFFF;border:1px solid #E3E6EB;">
            <tr>
              <td style="background-color:#0A1220;padding:26px 28px;">
                <p style="margin:0 0 8px;font-family:Helvetica,Arial,sans-serif;font-size:11px;letter-spacing:0.22em;text-transform:uppercase;color:#C6A45C;">Prime Nation Haul</p>
                <h1 style="margin:0;font-family:Helvetica,Arial,sans-serif;font-size:22px;line-height:1.25;color:#FFFFFF;">New ${escapeHtml(inquiryLabel)}</h1>
                <div style="height:2px;width:44px;background-color:#C6A45C;margin-top:16px;"></div>
              </td>
            </tr>
            <tr>
              <td style="padding:24px 28px 8px;">
                <p style="margin:0 0 4px;font-family:Helvetica,Arial,sans-serif;font-size:13px;color:#687386;">
                  Submitted ${escapeHtml(submittedAt)} · Website inquiry
                </p>
              </td>
            </tr>
            <tr>
              <td style="padding:4px 28px 20px;">
                <table role="presentation" width="100%" cellpadding="0" cellspacing="0">
                  ${rows}
                </table>
              </td>
            </tr>
            <tr>
              <td style="padding:0 28px 26px;">
                <div style="border-top:1px solid #E3E6EB;padding-top:16px;">
                  <p style="margin:0;font-family:Helvetica,Arial,sans-serif;font-size:12px;line-height:1.6;color:#687386;">
                    Reply directly to this email to reach the carrier at ${escapeHtml(replyTo)}. This notification was generated by the Prime Nation Haul website forms. Submissions are delivered by email and are not stored in an application database.
                  </p>
                </div>
              </td>
            </tr>
            <tr>
              <td style="background-color:#101D32;padding:16px 28px;">
                <p style="margin:0;font-family:Helvetica,Arial,sans-serif;font-size:11px;letter-spacing:0.12em;text-transform:uppercase;color:#C6A45C;">Prime Nation Haul · 316 376 9718</p>
              </td>
            </tr>
          </table>
        </td>
      </tr>
    </table>
  </body>
</html>`;

  const text = [
    "PRIME NATION HAUL",
    `New ${inquiryLabel}`,
    "",
    `Submitted: ${submittedAt}`,
    "",
    ...safeFields.map((field) => `${field.label}: ${escapeText(field.value)}`),
    "",
    `Reply to: ${replyTo}`,
    "Submissions are delivered by email and are not stored in an application database.",
  ].join("\n");

  return { html, text };
}
